"""nox configuration for LCFTP."""

import os
from collections.abc import Iterator
from contextlib import contextmanager

import nox
from nox_uv import session

# Default sessions.
nox.options.sessions = ["lint", "typing", "test"]

# Other nox defaults.
nox.options.default_venv_backend = "uv"
nox.options.reuse_existing_virtualenvs = True

# Test directories for packages that require Python 3.14.
_TEST_DIRS = ["tests", "models/tests", "auth/tests", "client/tests"]

# Packages that must also work on Python 3.13 (the RSP notebook kernel).
_PY313_PACKAGES = ["models", "client"]

# Test-only dependencies for the Python 3.13 session, which cannot use the
# workspace lock because the server requires Python 3.14.
_PY313_TEST_DEPS = ["pytest", "pytest-asyncio", "respx"]


@contextmanager
def _database_env() -> Iterator[dict[str, str]]:
    """Provide a PostgreSQL database URL for Alembic.

    Uses ``LCFTP_TEST_DATABASE_URL`` if set, otherwise starts a PostgreSQL
    container with testcontainers.

    Yields
    ------
    dict of str
        Environment variables to set when running Alembic.
    """
    if url := os.environ.get("LCFTP_TEST_DATABASE_URL"):
        yield {"LCFTP_DATABASE_URL": url}
        return

    from testcontainers.postgres import PostgresContainer  # noqa: PLC0415

    with PostgresContainer(
        driver="asyncpg",
        dbname="lcftp",
        username="lcftp",
        password=os.urandom(16).hex(),
    ) as postgres:
        yield {"LCFTP_DATABASE_URL": postgres.get_connection_url()}


@session(name="create-migration", uv_groups=["dev"])
def create_migration(session: nox.Session) -> None:
    """Create a database schema migration to the current schema."""
    message = session.posargs[0] if session.posargs else "Autogenerated"
    with _database_env() as env:
        session.run("alembic", "upgrade", "head", env=env)
        session.run(
            "alembic", "revision", "--autogenerate", "-m", message, env=env
        )


@session(name="coverage-report", uv_groups=["dev"])
def coverage_report(session: nox.Session) -> None:
    """Generate a code coverage report from the test suite."""
    session.run("coverage", "report", *session.posargs)


@session(uv_only_groups=["lint"], uv_no_install_project=True)
def lint(session: nox.Session) -> None:
    """Run pre-commit hooks."""
    session.run("pre-commit", "run", "--all-files", *session.posargs)


@session(uv_groups=["dev", "nox", "typing"])
def typing(session: nox.Session) -> None:
    """Check type annotations with mypy."""
    sources = ["noxfile.py", "src", "models/src", "auth/src", "client/src"]
    session.run("mypy", *session.posargs, *sources, "tests")
    # Test directories are checked separately because pytest's importlib
    # mode allows test modules with the same name in different packages.
    for test_dir in _TEST_DIRS[1:]:
        session.run("mypy", *session.posargs, test_dir)


@session(uv_groups=["dev"])
def test(session: nox.Session) -> None:
    """Run the test suite for all packages."""
    session.run(
        "pytest",
        *(session.posargs or _TEST_DIRS),
        env={"PYTHONASYNCIODEBUG": "1"},
    )


@nox.session(name="test-py313", python="3.13", venv_backend="uv")
def test_py313(session: nox.Session) -> None:
    """Test the packages that must run in the Python 3.13 RSP kernel."""
    session.install(*_PY313_TEST_DEPS, *(f"./{p}" for p in _PY313_PACKAGES))
    session.run(
        "pytest",
        "-p",
        "no:cacheprovider",
        *(session.posargs or [f"{p}/tests" for p in _PY313_PACKAGES]),
    )


@session(name="test-coverage", uv_groups=["dev"])
def test_coverage(session: nox.Session) -> None:
    """Run the test suite with coverage analysis."""
    session.run("coverage", "run", "-m", "pytest", *_TEST_DIRS)
